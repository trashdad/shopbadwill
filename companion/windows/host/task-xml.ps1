<#
.SYNOPSIS
  Pure task-definition logic for the ShopBadwill wake-and-launch companion:
  task names (always prefixed `ShopBadwill-`), the browser launch argument
  arrays, and the wake-task XML. The XML is generated by the Task Scheduler COM
  API (`ITaskService.NewTask(...).XmlText`): it builds an in-memory definition
  only and registers NOTHING, so tests may call it freely (controller ruling R1).

  Every schtasks command is built as an argument ARRAY, never a concatenated
  shell string (ruling R2). The only string serialization is the task XML
  `Arguments` attribute, which the Task Scheduler schema itself requires.
#>

$SbwTaskPrefix = 'ShopBadwill-'

function Get-SbwTaskName {
  param([string]$SnipeId)
  $SbwTaskPrefix + $SnipeId
}

function Test-SbwIsPath {
  param([string]$Value)
  ($Value -match '[\\/]') -or ($Value -cmatch '^[A-Za-z]:')
}

# Browser launch arguments for a profile NAME (`Default`, `default-release`)
# or a profile PATH (a user-data dir for Chrome, a profile dir for Firefox).
function Get-SbwBrowserArgs {
  param([string]$Browser, [string]$Profile)
  if ($Browser -ceq 'chrome') {
    if (Test-SbwIsPath -Value $Profile) { return ,@("--user-data-dir=$Profile") }
    return ,@("--profile-directory=$Profile")
  }
  if (Test-SbwIsPath -Value $Profile) { return ,@('-profile', $Profile) }
  ,@('-P', $Profile)
}

# CommandLineToArgvW quoting for one argv element. Task Scheduler's Exec
# Arguments is one string; the browser parses it. Quote only when the element
# is empty or contains whitespace or a quote. A backslash is literal except
# before a quote, where every backslash is doubled and the quote is escaped.
function ConvertTo-SbwArgvToken {
  param([string]$Arg)
  if ($null -eq $Arg) { $Arg = '' }
  if ($Arg.Length -gt 0 -and $Arg -notmatch '[\s"]') { return $Arg }
  $sb = New-Object System.Text.StringBuilder
  [void]$sb.Append('"')
  $slashes = 0
  foreach ($ch in $Arg.ToCharArray()) {
    if ($ch -eq '\') { $slashes++; continue }
    if ($ch -eq '"') {
      if ($slashes -gt 0) { [void]$sb.Append([char]92, ($slashes * 2)) }
      [void]$sb.Append('\"')
      $slashes = 0
      continue
    }
    if ($slashes -gt 0) { [void]$sb.Append([char]92, $slashes); $slashes = 0 }
    [void]$sb.Append($ch)
  }
  if ($slashes -gt 0) { [void]$sb.Append([char]92, ($slashes * 2)) }
  [void]$sb.Append('"')
  $sb.ToString()
}

# Exec action: the configured browser executable, and only its profile
# arguments. Nothing here is a shell. Returns @{ Execute; Arguments }.
function Get-SbwLaunchCommand {
  param([string]$ExePath, [string[]]$BrowserArgs)
  $tokens = @()
  foreach ($a in @($BrowserArgs)) { $tokens += (ConvertTo-SbwArgvToken -Arg ([string]$a)) }
  @{ Execute = $ExePath; Arguments = ($tokens -join ' ') }
}

# schtasks command argument arrays (R2): create from generated XML, cancel,
# query one task by its exact prefixed name.
function Get-SbwScheduleArgs {
  param([string]$TaskName, [string]$XmlPath)
  @('/Create', '/TN', $TaskName, '/XML', $XmlPath, '/F')
}

function Get-SbwCancelArgs {
  param([string]$TaskName)
  @('/Delete', '/TN', $TaskName, '/F')
}

function Get-SbwQueryArgs {
  param([string]$TaskName)
  @('/Query', '/TN', $TaskName, '/FO', 'CSV', '/NH')
}

# Builds the wake-task XML string (Task Scheduler 2.0 schema, in-memory only):
#   - one-off TimeTrigger at the LOCAL wall-clock of wakeAtUtc, EndBoundary +1 h
#     (a machine waking much later has missed the snipe anyway);
#   - WakeToRun (the wake timer), StartWhenAvailable, battery-tolerant;
#   - Exec action = the configured browser plus its profile arguments only;
#   - ExecutionTimeLimit PT0S so the scheduler does not kill that browser;
#   - DeleteExpiredTaskAfter PT10M so fired/orphaned tasks delete themselves;
#   - InteractiveToken / LeastPrivilege principal for the current user.
function New-SbwTaskXml {
  param(
    [string]$TaskName,
    [datetimeoffset]$WakeAtUtc,
    [string]$Execute,
    [string]$Arguments,
    [string]$UserId
  )
  $local = $WakeAtUtc.ToLocalTime()
  $start = $local.ToString('yyyy-MM-dd\THH:mm:ss', [Globalization.CultureInfo]::InvariantCulture)
  $end = $local.AddHours(1).ToString('yyyy-MM-dd\THH:mm:ss', [Globalization.CultureInfo]::InvariantCulture)

  $svc = New-Object -ComObject Schedule.Service
  $svc.Connect()
  $task = $svc.NewTask(0)

  $settings = $task.Settings
  $settings.Enabled = $true
  $settings.WakeToRun = $true
  $settings.StartWhenAvailable = $true
  $settings.DisallowStartIfOnBatteries = $false
  $settings.StopIfGoingOnBatteries = $false
  $settings.ExecutionTimeLimit = 'PT0S'
  $settings.DeleteExpiredTaskAfter = 'PT10M'
  $settings.MultipleInstances = 2   # TASK_INSTANCES_IGNORE_NEW

  $trigger = $task.Triggers.Create(1)   # TASK_TRIGGER_TIME (one-off)
  $trigger.StartBoundary = $start
  $trigger.EndBoundary = $end
  $trigger.Enabled = $true

  $action = $task.Actions.Create(0)     # TASK_ACTION_EXEC
  $action.Path = $Execute
  $action.Arguments = $Arguments

  $principal = $task.Principal
  $principal.LogonType = 3              # TASK_LOGON_INTERACTIVE_TOKEN
  $principal.RunLevel = 0               # TASK_RUNLEVEL_LUA (least privilege)
  $principal.UserId = $UserId

  $task.XmlText
}
